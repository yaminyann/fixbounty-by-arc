// Regenerates the typed ABI modules for the frontend and the server from the Foundry build.
//   forge build && bun run abi
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const artifactPath = path.join(root, 'contracts/out/BountyBoard.sol/BountyBoard.json')

if (!fs.existsSync(artifactPath)) {
  console.error('Missing build artifact. Run `forge build` first.')
  process.exit(1)
}

const { abi } = JSON.parse(fs.readFileSync(artifactPath, 'utf8')) as { abi: unknown }
const body = `export const BOUNTY_BOARD_ABI = ${JSON.stringify(abi, null, 2)} as const\n`
const header = '// Generated by scripts/export-abi.mjs from contracts/BountyBoard.sol. Do not edit.\n'

for (const target of ['src/lib/bountyBoardAbi.ts', 'server/src/abi.ts']) {
  fs.writeFileSync(path.join(root, target), header + body)
  console.log(`wrote ${target}`)
}
